function ok=uni01_accept(r,t)
% Evaluation only: transmitted ground truth never enters uni01_rx.
ok=~isempty(r) && ~r.crcError && r.cellID==t.config.cellID ...
    && r.ssbIndex==t.config.ssbIndex && isequal(r.mibBits,t.mibBits) ...
    && r.systemFrameNumber==t.config.systemFrameNumber ...
    && r.halfFrame==t.config.halfFrame && r.kSsb==t.config.kSsb;
end
